function capacityTotals(actions, byId) {
    const targets = new Map();
    for (const { actorId, method, target } of actions) {
        const actor = byId.get(actorId);
        const capacity = actor.activeBodyParts.heal * (method === 'heal' ? 12 : 4);
        targets.set(target.id, (targets.get(target.id) ?? 0) + capacity);
    }
    let nominal = 0, useful = 0;
    for (const [id, capacity] of targets) {
        const target = byId.get(id);
        nominal += capacity;
        useful += Math.min(capacity, target.hitsMax - target.hits);
    }
    return [nominal, useful, nominal - useful];
}

for (const snapshot of fixture.snapshots) {
    test(`recorded tick ${snapshot.tick}: all three capacity-aware healing decisions`, () => {
        const creeps = snapshot.creeps.map(record => recordedCreep(record));
        const friends = freeze(creeps.filter(creep => creep.my && creep.hits > 0 && creep.hits < creep.hitsMax));
        const healers = [1, 2, 3].map(i => creeps.find(creep => creep.id === ownId(`healer_${i}`)));
        const actual = healers.map(healer => actionKey(selectHealingAction(healer, friends)));
        assert.deepEqual(actual, expected[snapshot.tick - 36]);
        // Input order, actor evaluation order and repeated calls cannot reserve healing.
        assert.deepEqual([...healers].reverse().map(healer =>
            actionKey(selectHealingAction(healer, freeze([...friends].reverse())))).reverse(), actual);
        for (const creep of creeps) {
            const counts = {};
            for (const part of creep.body) counts[part.type] = (counts[part.type] ?? 0) + 1;
            assert.deepEqual(counts, creep.activeBodyParts);
        }
    });
}

test('recorded full rosters preserve 128 movement decisions, 83 moves and 38 attack calls', () => {
    const normalizeAction = a => ({ method: a.method, target: { id: a.target.id, x: a.target.x, y: a.target.y },
        targetKind: a.targetKind ?? a.target.kind });
    const normalizeDecision = d => ({ phase: d.phase, channel: d.channel, actorId: d.actorId,
        outcome: d.outcome, reason: d.reason, actions: d.actions.map(normalizeAction) });
    const normalizeAttempt = a => ({ actorId: a.actorId, method: a.method,
        target: { id: a.target.id, x: a.target.x, y: a.target.y } });
    const engagements = new Map();
    let movements = 0, moves = 0, attacks = 0;
    const historicalTotals = [], candidateTotals = [];
    for (const snapshot of fixture.snapshots) {
        const calls = [], decisions = [], attempts = [], events = [];
        const creeps = snapshot.creeps.map(record => recordedCreep(record, calls));
        const byId = new Map(creeps.map(creep => [creep.id, creep]));
        const own = freeze(creeps.filter(creep => creep.my));
        const enemies = freeze(creeps.filter(creep => !creep.my && creep.hits > 0));
        const injured = freeze(own.filter(creep => creep.hits > 0 && creep.hits < creep.hitsMax));
        const flagRecord = snapshot.flags.find(flag => flag.id === snapshot.selectedFlagId);
        const flag = freeze({ ...flagRecord, my: flagRecord.owner === 'me' });
        const reporter = {
            decision(d) { decisions.push(normalizeDecision(d)); events.push(['decision', d.actorId, d.channel]); return d; },
            attempt(d, index, a, returnCode) {
                assert.equal(returnCode, 0);
                assert.deepEqual(normalizeAction(a), normalizeAction(d.actions[index]));
                attempts.push(normalizeAttempt({ ...a, actorId: d.actorId }));
                events.push(['attempt', d.actorId, d.channel]);
            },
        };
        // First engagement is tick 36. No escort movement appears in this trace;
        // allocation, holding and pairing were disabled. No engine state is advanced.
        moveCreeps(own, enemies, flag, engagements, new Map(), null, null, reporter);
        executeTactics(own, enemies, injured, reporter);
        const historical = original.filter(d => d.tick === snapshot.tick);
        for (const channel of ['movement', 'combat']) {
            assert.deepEqual(decisions.filter(d => d.channel === channel), historical
                .filter(d => d.type === 'action-decision' && d.channel === channel).map(normalizeDecision));
        }
        assert.deepEqual(calls.filter(a => !['heal', 'rangedHeal'].includes(a.method)), historical
            .filter(d => d.type === 'action-attempt' && d.channel !== 'healing').map(normalizeAttempt));
        assert.deepEqual(attempts, calls);
        for (const actor of own) {
            const eventsForActor = events.filter(e => e[1] === actor.id);
            const healDecision = eventsForActor.findIndex(e => e[0] === 'decision' && e[2] === 'healing');
            const combatDecision = eventsForActor.findIndex(e => e[0] === 'decision' && e[2] === 'combat');
            assert.ok(healDecision >= 0 && combatDecision > healDecision);
            const healAttempt = eventsForActor.findIndex(e => e[0] === 'attempt' && e[2] === 'healing');
            if (healAttempt >= 0) assert.ok(healAttempt > healDecision && healAttempt < combatDecision);
        }
        movements += decisions.filter(d => d.channel === 'movement').length;
        moves += calls.filter(a => a.method === 'moveTo').length;
        attacks += calls.filter(a => ['attack', 'rangedAttack'].includes(a.method)).length;
        historicalTotals.push(capacityTotals(historical.filter(d => d.type === 'action-attempt' && d.channel === 'healing'), byId));
        candidateTotals.push(capacityTotals(calls.filter(a => ['heal', 'rangedHeal'].includes(a.method)), byId));
    }
    assert.deepEqual([movements, moves, attacks], [128, 83, 38]);
    assert.deepEqual(historicalTotals.map(t => t[1]), [0, 0, 24, 78, 66, 54, 82, 4, 120, 120]);
    assert.deepEqual(candidateTotals.map(t => t[1]), [0, 0, 24, 84, 102, 102, 120, 120, 120, 120]);
    const sum = rows => [0, 1, 2].map(i => rows.reduce((total, row) => total + row[i], 0));
    assert.deepEqual(sum(historicalTotals), [1176, 548, 628]);
    assert.deepEqual(sum(candidateTotals), [936, 792, 144]);
});

