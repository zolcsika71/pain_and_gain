test('self is considered exactly once and candidate input arrays are not mutated', () => {
    const ranges = [];
    const actor = { ...unit('actor', 0, 0, { hits: 96 }),
        getRangeTo(target) { ranges.push(target.id); return Math.max(Math.abs(target.x), Math.abs(target.y)); } };
    const ally = unit('ally', 2, 0, { hits: 1 });
    const input = freeze([actor, ally, actor, ally]);
    assert.equal(selectHealingAction(actor, input).target, actor); // 4 versus 4: self wins range tie.
    assert.deepEqual(ranges, ['actor', 'ally']);
    assert.deepEqual(input, [actor, ally, actor, ally]);
});

test('living owned actors need functioning HEAL; targets must be living, owned and injured', () => {
    const ally = unit('ally', 1, 0, { hits: 50 });
    for (const options of [{ my: false }, { hits: 0 }, { activeBodyParts: {} }]) {
        assert.equal(selectHealingAction(unit('actor', 0, 0, options), [ally]), null);
    }
    const broken = { ...unit('actor'), body: [{ type: 'heal', hits: 0 }] };
    assert.equal(selectHealingDecision(broken, [ally]).reason, 'no-functioning-heal');
    const actor = unit('actor');
    assert.equal(selectHealingAction(actor, [unit('enemy', 1, 0, { my: false, hits: 1 }),
        unit('dead', 1, 0, { hits: 0 }), unit('healthy', 1, 0), unit('far', 4, 0, { hits: 1 })]), null);
});

test('self competes by capped capacity; functioning-part count changes the choice', () => {
    const ally = unit('ally', 2, 0, { hits: 20 });
    const onePart = unit('actor', 0, 0, { hits: 94 });
    const twoParts = unit('actor', 0, 0, { hits: 94, activeBodyParts: { heal: 2 } });
    assert.equal(selectHealingAction(onePart, [ally]).target, onePart); // 6 versus 4
    assert.equal(selectHealingAction(twoParts, [ally]).target, ally); // 6 versus 8
    const partlyBroken = { ...onePart, body: [{ type: 'heal', hits: 1 }, { type: 'heal', hits: 0 }] };
    assert.equal(selectHealingAction(partlyBroken, [ally]).target, partlyBroken);
    const tinySelf = unit('actor', 0, 0, { hits: 98 });
    assert.equal(selectHealingAction(tinySelf, [tinySelf, ally, tinySelf]).target, ally);
    assert.equal(selectHealingAction(onePart, []).target, onePart);
});

test('range boundaries and direct capacity take precedence over a larger distant deficit', () => {
    const actor = unit('actor');
    for (const [x, method] of [[1, 'heal'], [2, 'rangedHeal'], [3, 'rangedHeal']]) {
        assert.equal(selectHealingAction(actor, [unit('ally', x, x, { hits: 1 })]).method, method);
    }
    assert.equal(selectHealingAction(actor, [unit('far', 4, 0, { hits: 1 })]), null);
    const near = unit('z', 1, 1, { hits: 89 }), far = unit('a', 2, 0, { hits: 1 });
    assert.equal(selectHealingAction(actor, [far, near]).target, near); // 11 versus 4
});

test('ties use range then ID, not uncapped deficit, input order or role', () => {
    const actor = unit('actor');
    const near = unit('z', 2, 0, { hits: 90 }), far = unit('a', 3, 0, { hits: 1 });
    assert.equal(selectHealingAction(actor, [far, near]).target, near);
    const smallerId = unit('a', 2, 0, { hits: 90 }), largerId = unit('z', 0, 2, { hits: 1 });
    for (const candidates of [[largerId, smallerId], [smallerId, largerId]]) {
        assert.equal(selectHealingAction(actor, freeze(candidates)).target, smallerId);
    }
    const self = unit('actor', 0, 0, { hits: 88 });
    assert.equal(selectHealingAction(self, [unit('a', 1, 0, { hits: 1 }), self, self]).target, self);
});

