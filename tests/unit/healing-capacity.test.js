function recordedCreep(record, calls = []) {
    const creep = {
        ...record,
        // Presence-only adapter: 1 is an eligibility sentinel, NOT observed
        // per-part HP. Preserve every recorded functioning count exactly.
        body: Object.entries(record.activeBodyParts).flatMap(([type, count]) =>
            Array.from({ length: count }, () => ({ type, hits: 1 }))),
        getRangeTo(target) { return Math.max(Math.abs(this.x - target.x), Math.abs(this.y - target.y)); },
    };
    for (const method of ['moveTo', 'heal', 'rangedHeal', 'attack', 'rangedAttack']) {
        creep[method] = target => {
            calls.push({ actorId: creep.id, method, target: { id: target.id, x: target.x, y: target.y } });
            return 0; // Mock scheduling only; never alter HP, parts or positions.
        };
    }
    return freeze(creep);
}

function unit(id, x = 0, y = 0, options = {}, calls = []) {
    return recordedCreep({ id, x, y, my: true, hits: 100, hitsMax: 100, fatigue: 0,
        activeBodyParts: { heal: 1 }, ...options }, calls);
}
const actionKey = action => action ? [short(action.target.id), action.method] : null;

